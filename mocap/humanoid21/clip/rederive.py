"""Rederive velocity fields from the pose trajectory.

Pose is primary; interior velocities are (re)generated by centered
finite differences so that the stored velocity is exactly consistent
with the stored poses:

    joint_vel_norm[k]        = (jp[k+1] - jp[k-1]) / (2·dt)
    root_vel_local[k]        = R[k]^T · (rp[k+1] - rp[k-1]) / (2·dt)
    root_angular_vel_local[k]= R[k]^T · log(R[k-1]^{-1}·R[k+1])/(2dt)

Endpoint frames keep the recorded values by default (they carry
transition semantics from the longer source trajectory);
``zero_endpoints=True`` forces them to zero — useful for
"start-from-rest / end-at-rest" clips.

This is a KINEMATIC repair: it makes velocity consistent with poses,
it does not make the motion dynamically feasible, and it LOSES the
extra information carried by velocities recorded at a higher source
rate (e.g. 120 Hz mocap downsampled to 20 Hz).  The caller decides
when rederiving is a repair (after pose edits / groundfix) vs a
downgrade (untouched refclip conversions).
"""
from __future__ import annotations

import numpy as np

from .checks import _quat_inv_wxyz, _quat_log_wxyz, _quat_mul_wxyz, _rot
from .core_clip import CONTROL_DT, CoreClip, record_lineage


def rederive_velocities(clip: CoreClip,
                        zero_endpoints: bool = False) -> CoreClip:
    T = clip.T
    states = {f: v.copy() for f, v in clip.states.items()}
    if T >= 3:
        dt2 = 2.0 * CONTROL_DT
        jp = clip.states["joint_pos_norm"].astype(np.float64)
        rp = clip.states["root_pos"].astype(np.float64)
        rq = clip.states["root_rot"].astype(np.float64)

        states["joint_vel_norm"][1:-1] = (jp[2:] - jp[:-2]) / dt2
        for k in range(1, T - 1):
            R = _rot(rq[k])
            vw = (rp[k + 1] - rp[k - 1]) / dt2
            states["root_vel_local"][k] = R.T @ vw
            dq = _quat_mul_wxyz(_quat_inv_wxyz(rq[k - 1]), rq[k + 1])
            states["root_angular_vel_local"][k] = \
                R.T @ (_quat_log_wxyz(dq) / dt2)
    if zero_endpoints:
        states["joint_vel_norm"][0] = 0.0
        states["joint_vel_norm"][-1] = 0.0
        states["root_vel_local"][0] = 0.0
        states["root_vel_local"][-1] = 0.0
        states["root_angular_vel_local"][0] = 0.0
        states["root_angular_vel_local"][-1] = 0.0

    meta = dict(clip.meta)
    meta["clip_id"] = f"{clip.clip_id}_vel"
    meta["source"] = {"type": "rederive_vel", "parent": clip.clip_id,
                      "method": "centered_finite_difference",
                      "endpoints": "zeroed" if zero_endpoints
                      else "kept_recorded",
                      "note": "kinematic consistency only — not a "
                              "feasibility statement"}
    meta = record_lineage(meta, "rederive_vel", parent=clip.clip_id,
                          zero_endpoints=zero_endpoints)
    return CoreClip(states, meta,
                    None if clip.ref_action is None
                    else clip.ref_action.copy())
