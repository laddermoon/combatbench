"""Path-based reclip optimizer.

This module implements the approved reclip model: a pose-only TargetPath
provides geometry, an ObjectiveEvaluator provides progress/event scoring,
and a sweep optimizer evaluates candidate actions by their full suffix
rollout.  The output clip is then regenerated by one complete replay
from the initial simulator state.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np

from .core_clip import (CONTROL_DT, CORE_FIELDS, PHY_DT, CoreClip,
                        SPEC_VERSION, record_lineage)
from .objective_evaluator import (ObjectiveEvaluator,
                                  ReclipObjectiveConfig,
                                  RolloutEvaluation)
from .target_path import TargetPath, pose_error


@dataclass
class PathRollout:
    states: List[Dict[str, np.ndarray]]
    evaluation: RolloutEvaluation


@dataclass
class ReclipSolveResult:
    clip: CoreClip
    evaluation: RolloutEvaluation
    actions: np.ndarray
    replay_metrics: Dict[str, float]
    solver_seed: int


def _phys_steps() -> int:
    return int(round(CONTROL_DT / PHY_DT))


def execute_actions(sim, robot: str, other: str,
                    start_state: Dict[str, np.ndarray],
                    other_state: Dict[str, np.ndarray],
                    actions: np.ndarray
                    ) -> List[Dict[str, np.ndarray]]:
    """Execute one control-rate action sequence and return all states."""
    sim.set_core_state({robot: dict(start_state), other: other_state})
    states = [dict(start_state)]
    zero = np.zeros(21, np.float32)
    for a in np.asarray(actions, dtype=np.float32):
        sim.set_action({robot: a, other: zero})
        for _ in range(_phys_steps()):
            sim.physical_step()
        states.append(sim.get_core_state()[robot])
    return states


def roll_actions(sim, robot: str, other: str,
                 start_state: Dict[str, np.ndarray],
                 other_state: Dict[str, np.ndarray],
                 actions: np.ndarray,
                 evaluator: ObjectiveEvaluator,
                 start_s: float,
                 frame_offset: int = 0) -> PathRollout:
    states = execute_actions(sim, robot, other, start_state,
                             other_state, actions)
    ev = evaluator.evaluate_rollout(
        states, actions, start_s=start_s, frame_offset=frame_offset)
    return PathRollout(states=states, evaluation=ev)


def pd_init_actions(path: TargetPath, budget_frames: int,
                    start_s: float = 0.0) -> np.ndarray:
    """Use next path joint poses as normalized PD-target actions."""
    if budget_frames <= 0:
        return np.zeros((0, 21), np.float32)
    s = np.linspace(start_s, min(path.s_max, path.s_end),
                    budget_frames + 1)[1:]
    return np.stack([np.clip(path.sample(float(v)).joint_pos_norm,
                             -1.0, 1.0) for v in s]).astype(np.float32)


def _prepare_actions(init_actions: Optional[np.ndarray],
                     path: TargetPath, budget_frames: int,
                     start_s: float) -> np.ndarray:
    if init_actions is None:
        return pd_init_actions(path, budget_frames, start_s)
    a = np.asarray(init_actions, dtype=np.float32)
    if a.ndim != 2 or a.shape[1] != 21:
        raise ValueError("init_actions must have shape (N,21)")
    if len(a) >= budget_frames:
        return np.clip(a[:budget_frames], -1.0, 1.0)
    pad = np.zeros((budget_frames - len(a), 21), np.float32)
    if len(a):
        pad[:] = np.clip(a[-1], -1.0, 1.0)
    return np.vstack([np.clip(a, -1.0, 1.0), pad])


def replay_error_metrics(sim, robot: str, other: str,
                         start_state: Dict[str, np.ndarray],
                         other_state: Dict[str, np.ndarray],
                         actions: np.ndarray,
                         expected: Sequence[Dict[str, np.ndarray]]
                         ) -> Dict[str, float]:
    """Replay output actions once more and compare every CoreState field."""
    got = execute_actions(sim, robot, other, start_state, other_state,
                          actions)
    if len(got) != len(expected):
        raise RuntimeError(
            f"replay length {len(got)} != expected {len(expected)}")

    jp = np.zeros(len(got))
    jv = np.zeros(len(got))
    rp = np.zeros(len(got))
    rq = np.zeros(len(got))
    rv = np.zeros(len(got))
    ra = np.zeros(len(got))
    for i, (a, b) in enumerate(zip(got, expected)):
        jp[i] = np.abs(a["joint_pos_norm"] - b["joint_pos_norm"]).mean()
        jv[i] = np.abs(a["joint_vel_norm"] - b["joint_vel_norm"]).mean()
        rp[i] = np.linalg.norm(a["root_pos"] - b["root_pos"])
        pa = pose_error(a, b)
        rq[i] = pa["components"]["rq"]
        rv[i] = np.linalg.norm(a["root_vel_local"]
                               - b["root_vel_local"])
        ra[i] = np.linalg.norm(a["root_angular_vel_local"]
                               - b["root_angular_vel_local"])
    return {
        "joint_pos_err_mean_max": float(jp.max()),
        "joint_pos_err_mean_final": float(jp[-1]),
        "joint_vel_err_mean_max": float(jv.max()),
        "root_pos_err_max": float(rp.max()),
        "root_rot_err_max": float(rq.max()),
        "root_vel_err_max": float(rv.max()),
        "root_angvel_err_max": float(ra.max()),
    }


def reclip_path_sweep(
        start: Dict[str, np.ndarray],
        path: TargetPath,
        objective: ReclipObjectiveConfig,
        init_actions: Optional[np.ndarray] = None,
        budget_frames: Optional[int] = None,
        robot: str = "robot_a",
        sweeps: int = 3,
        n_samples: int = 32, n_iters: int = 2,
        sigma0: float = 0.15,
        seed: int = 0, sim=None,
        start_s: float = 0.0,
        post_frames: int = 0,
        clip_id: str = "reclip") -> ReclipSolveResult:
    """Optimize an action sequence against a continuous TargetPath.

    Candidate actions at frame k are scored by the evaluator over the
    entire remaining action suffix.  Thus an action is rewarded for
    enabling future progress, not just for the next landing pose.
    """
    own = sim is None
    if own:
        from .rederive_action import _mk_sim
        sim = _mk_sim()
    rng = np.random.default_rng(seed)
    other = "robot_b" if robot == "robot_a" else "robot_a"
    other_state = sim.get_core_state()[other]
    evaluator = ObjectiveEvaluator(path, objective)
    budget = (objective.time_budget_frames if budget_frames is None
              else int(budget_frames))
    if budget <= 0:
        raise ValueError("budget_frames must be positive")
    seq = _prepare_actions(init_actions, path, budget, start_s)

    def suffix_roll(k: int, suffix: np.ndarray) -> PathRollout:
        return roll_actions(sim, robot, other, states[k], other_state,
                            suffix, evaluator, start_s=progress[k],
                            frame_offset=k)

    full = roll_actions(sim, robot, other, start, other_state,
                        seq, evaluator, start_s=start_s)
    states = full.states
    progress = full.evaluation.progress.copy()

    for _ in range(int(sweeps)):
        for k in range(budget):
            best = suffix_roll(k, seq[k:])
            best_a = seq[k]
            mu = seq[k].copy()
            sigma = np.full(21, sigma0, dtype=np.float64)
            for it in range(int(n_iters)):
                cand = np.clip(rng.normal(mu, sigma,
                                          (int(n_samples), 21)),
                               -1.0, 1.0).astype(np.float32)
                if it == 0:
                    cand[0] = seq[k]
                for c in cand:
                    trial_suffix = seq[k:].copy()
                    trial_suffix[0] = c
                    trial = suffix_roll(k, trial_suffix)
                    if trial.evaluation.score < best.evaluation.score:
                        best = trial
                        best_a = c
                mu = 0.7 * mu + 0.3 * best_a
                sigma = np.maximum(0.5 * sigma, 0.03)
            seq[k] = best_a
            states[k + 1:] = best.states[1:]
            progress[k:] = best.evaluation.progress

    # Required final pass: regenerate the output trajectory by replaying
    # the selected sequence once from the initial complete CoreState.
    replay_states = execute_actions(sim, robot, other, start,
                                    other_state, seq)
    full_eval = evaluator.evaluate_rollout(replay_states, seq,
                                           start_s=start_s)

    if objective.kind != "track" and full_eval.event_frame is not None:
        end_idx = min(len(replay_states) - 1,
                      full_eval.event_frame + int(post_frames))
    else:
        end_idx = len(replay_states) - 1
    out_states = replay_states[:end_idx + 1]
    out_actions = seq[:end_idx]
    out_eval = evaluator.evaluate_rollout(out_states, out_actions,
                                          start_s=start_s)

    # Independent second replay: verifies the emitted CoreClip action
    # sequence against every stored CoreState field.
    replay_metrics = replay_error_metrics(
        sim, robot, other, start, other_state, out_actions, out_states)
    if own:
        sim.close()

    T = len(out_states)
    ra = np.zeros((T, 21), np.float32)
    ra[:len(out_actions)] = out_actions.astype(np.float32)
    ra[T - 1] = np.clip(out_states[-1]["joint_pos_norm"], -1, 1)
    event = None
    if objective.kind != "track" and out_eval.event_frame is not None:
        event = {
            "type": "pass" if objective.kind == "pass" else "reach",
            "frame": out_eval.event_frame,
            "time": out_eval.event_frame * CONTROL_DT,
        }
    meta: Dict[str, Any] = {
        "spec_version": SPEC_VERSION,
        "clip_id": clip_id,
        "ref_action_semantics": "executed_pd_target",
        "source": {"type": "reclip", "parent": path.source_clip_id},
        "reclip": {
            "objective": objective.kind,
            "status": out_eval.status,
            "path": {
                "mode": path.mode,
                "source_clip_id": path.source_clip_id,
                "frame_indices": path.frame_indices.tolist(),
                "knot_s": path.knot_s.tolist(),
                "s_end": path.s_end,
                "s_ext": path.s_ext,
                "s_max": path.s_max,
            },
            "solver": {
                "method": "path_sweep",
                "budget_frames": budget,
                "sweeps": sweeps,
                "n_samples": n_samples,
                "n_iters": n_iters,
                "sigma0": sigma0,
                "seed": seed,
                "post_frames": int(post_frames),
            },
            "event": event,
            "solver_score": float(full_eval.score),
            "progress": out_eval.progress.tolist(),
            "pose_error_by_frame": [
                float(e["total"]) for e in out_eval.pose_errors],
            "metrics": dict(out_eval.metrics),
            "replay_error": replay_metrics,
            "note": "earliest/best result found under this solver and "
                    "budget; not a global minimum-time proof",
        },
    }
    meta = record_lineage(
        meta, "reclip", parent=path.source_clip_id, clip_id=clip_id,
        objective=objective.kind, path_mode=path.mode,
        budget_frames=budget, status=out_eval.status)
    stacked = {f: np.stack([s[f] for s in out_states])
               for f in CORE_FIELDS}
    return ReclipSolveResult(
        clip=CoreClip(stacked, meta, ra), evaluation=out_eval,
        actions=out_actions, replay_metrics=replay_metrics,
        solver_seed=seed)


def reclip_path_search(
        start: Dict[str, np.ndarray],
        path: TargetPath,
        objective: ReclipObjectiveConfig,
        init_actions: Optional[np.ndarray] = None,
        seeds: Sequence[int] = (0,),
        **kwargs) -> ReclipSolveResult:
    """Try several CEM seeds and return the lowest-scoring result."""
    results = [reclip_path_sweep(start, path, objective,
                                 init_actions=init_actions,
                                 seed=int(seed), **kwargs)
               for seed in seeds]
    return min(results, key=lambda r: (
        0 if r.evaluation.status == "completed" else 1,
        r.evaluation.score))
