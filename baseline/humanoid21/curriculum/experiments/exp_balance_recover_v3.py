"""Balance recovery v3: train with pre-generated state bank.

Uses StateBankInitPlugin to inject perturbed states from a .npz state bank
(generated by generate_state_bank.py) instead of running on-the-fly impulse
simulation. This decouples state generation from training, enabling iterative
curriculum: generate → train → re-generate near boundary → retrain.

Key differences from v2_pure:
  - StateBankInitPlugin replaces InitialStatePerturbationPlugin
  - Perturbation states come from a pre-generated bank (physically realistic)
  - Curriculum = different state bank files (gen0, gen1, ...) with increasingly
    harder states near the recovery boundary
  - Supports warm-start from a base policy (the one used to generate the bank)

Configuration via environment variables (no framework changes needed)::

    STATE_BANK_PATH=baseline/runs/recovery_iter/gen0_state_bank.npz \\
    BASE_POLICY_PATH=baseline/runs/train_basic_balance_v2_standup_ppo_20260801_003425/policy \\
    python3 baseline/framework/train.py --experiment balance_recover_v3 --algo ppo \\
        --run-name recover_v3_gen0

    # Smoke test
    STATE_BANK_PATH=/tmp/state_bank_verify.npz \\
    python3 baseline/framework/train.py --experiment balance_recover_v3 --algo ppo --smoke
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Tuple

import os

import numpy as np
import torch

from baseline.humanoid21.curriculum.experiments.base import CombatExperimentBase
from envs.framework.blueprint import EnvBlueprint
from envs.framework.parameterized_blueprint import ParameterizedEnvBlueprint
from envs.framework.policy import PolicyBlueprint


class BalanceRecoverV3Config(CombatExperimentBase):
    """Balance-recovery v3: state-bank-driven training with pure survival reward.

    Each episode loads a perturbed state from a pre-generated .npz state bank.
    Reward = per-step survival bonus + terminal fall/survive signal.
    No reward observers — maximizes rollout speed.
    """

    name = "balance_recover_v3"
    reward_keys = ("r_fall",)
    gammas = {"r_fall": 0.99}

    max_steps = 600

    BLUEPRINT = "balance_recover_v3_env.yaml"

    # --- PPO tuning ---
    log_std_min: float = -1.8

    max_updates: int = 20000
    learning_rate: float = 3e-5
    target_kl: float = 0.05
    grad_clip_norm: float = 1.0
    update_epochs: int = 4
    entropy_coef: float = 1.5e-3

    # --- Rollout schedule ---
    episodes_per_update: int = 2048
    eval_episodes: int = 128

    # --- Reward ---
    per_step_survival_reward: float = 0.01

    # --- Default custom config ---
    DEFAULT_CUSTOM_CONFIG: Dict[str, Any] = {
        "rollout_distance_min": 1.5,
        "rollout_distance_max": 3.5,
        "max_steps": 600,
        "terminal_fall_penalty": 1.0,
        "state_bank_path": None,
        "base_policy_path": None,
    }

    def _env_pb(self) -> ParameterizedEnvBlueprint:
        return ParameterizedEnvBlueprint.load(
            Path(__file__).resolve().parent.parent.parent / "blueprints" / self.BLUEPRINT
        )

    def _state_bank_path(self) -> str:
        p = os.environ.get("STATE_BANK_PATH")
        if not p:
            raise ValueError(
                "balance_recover_v3 requires STATE_BANK_PATH environment variable. "
                "Example: STATE_BANK_PATH=baseline/runs/recovery_iter/gen0_state_bank.npz"
            )
        return str(Path(p).resolve())

    def video_env_blueprint(self) -> EnvBlueprint:
        return self._env_pb().materialize(
            max_steps=self.max_steps,
            agent_id="robot_a",
            tolerance=6,
            state_bank_path=self._state_bank_path(),
            state_bank_seed=42,
        )

    # --- Actor warm-start from base policy ---
    def build_actor(self, device: torch.device) -> Any:
        from baseline.common.policies.tanh_gaussian_mlp import TanhGaussianMLPPolicy

        base_path = os.environ.get("BASE_POLICY_PATH")
        if not base_path:
            return super().build_actor(device)

        model_pt = Path(base_path) / "model.pt"
        if not model_pt.exists():
            raise FileNotFoundError(f"model.pt not found at {model_pt}")

        payload = torch.load(model_pt, map_location="cpu")
        hidden_dim = int(payload.get("hidden_dim", payload.get("actor_hidden_dim", 256)))

        actor = TanhGaussianMLPPolicy(
            obs_dim=int(payload["obs_dim"]),
            action_dim=int(payload["action_dim"]),
            hidden_dim=hidden_dim,
            log_std_min=float(self.log_std_min),
            log_std_max=float(self.log_std_max),
            device=device,
        )
        actor.load_state_dict(payload["state_dict"], strict=False)
        actor = actor.to(device)
        actor.log_std_min = float(self.log_std_min)
        return actor

    # --- Rollout job construction ---
    def _build_state_bank_jobs(
        self,
        policy_bp: PolicyBlueprint,
        base_seed: int,
        n_episodes: int,
    ) -> List[Tuple[PolicyBlueprint, PolicyBlueprint, EnvBlueprint, int, Dict[str, Any]]]:
        max_steps = self.max_steps
        env_pb = self._env_pb()
        bank_path = self._state_bank_path()
        rng = np.random.default_rng(base_seed)

        env_bps: Dict[str, EnvBlueprint] = {
            aid: env_pb.materialize(
                max_steps=max_steps,
                agent_id=aid,
                tolerance=6,
                state_bank_path=bank_path,
                state_bank_seed=int(base_seed),
            )
            for aid in ("robot_a", "robot_b")
        }

        jobs: List[Tuple[PolicyBlueprint, PolicyBlueprint, EnvBlueprint, int, Dict[str, Any]]] = []
        for i in range(n_episodes):
            seed = int(base_seed + i)
            agent_id = self._agent_from_rollout_seed(seed)
            initial_distance = float(
                rng.uniform(
                    self.custom_config["rollout_distance_min"],
                    self.custom_config["rollout_distance_max"],
                )
            )
            jobs.append((
                policy_bp, policy_bp,
                env_bps[agent_id], seed,
                {"agent_id": agent_id, "initial_distance": initial_distance},
            ))
        return jobs

    def build_rollout_jobs(self, policy_bp: PolicyBlueprint, base_seed: int):
        return self._build_state_bank_jobs(policy_bp, base_seed, self.episodes_per_update)

    def build_eval_jobs(self, policy_bp: PolicyBlueprint, base_seed: int):
        return self._build_state_bank_jobs(policy_bp, base_seed, self.eval_episodes)

    # --- Evaluation ---
    def compare_eval(self, esum, best_esum):
        if not best_esum:
            return True
        return esum.get("survived", 0.0) > best_esum.get("survived", 0.0)

    def next_weights(
        self,
        eval_metrics: Dict[str, float],
        current_weights: Tuple[float, ...],
    ) -> Tuple[float, ...]:
        return (1.0,)

    def initial_weights(self) -> Tuple[float, ...]:
        return (1.0,)

    # --- Reward extraction ---
    def extract_rewards(self, episode) -> Dict[str, np.ndarray]:
        T = episode.num_frames
        fell = "imbalance" in episode.termination_proposals
        r_fall = np.full(T, self.per_step_survival_reward, dtype=np.float32)
        penalty = float(self.custom_config["terminal_fall_penalty"])
        if fell:
            r_fall[-1] = -penalty
        else:
            r_fall[-1] = penalty
        return {"r_fall": r_fall}

    def compute_episode_metrics(self, episode) -> Dict[str, float]:
        fell = "imbalance" in episode.termination_proposals
        return {
            "survived": 0.0 if fell else 1.0,
            "ep_length": float(episode.num_frames),
        }

    def scheduler_info(self) -> Dict[str, Any]:
        return {
            "state_bank_path": os.environ.get("STATE_BANK_PATH", ""),
            "base_policy_path": os.environ.get("BASE_POLICY_PATH", ""),
        }

    def scheduler_state(self) -> dict:
        return {}

    def load_scheduler_state(self, state: dict) -> None:
        pass


# Singleton instance for the registry
EXPERIMENT = BalanceRecoverV3Config()
