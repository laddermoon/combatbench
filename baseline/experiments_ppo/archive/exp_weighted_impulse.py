"""V2 dual-agent experiment: weighted impulse perturbation training.

Same reward design as exp_basic_balance_v2_phi_dual_fixaw_survonly_crossphi2_impulse.py
but uses RelativeImpulsePlugin with per-episode impulse params sampled from
a boundary-weighted distribution (generated by sample_distribution.py from
probe_boundary.py scan results).

  - r_fall: 0.01 × φ(t) per step, no fall penalty, no timeout bonus
  - r_cross: alternating step reward/penalty, actor weight = 1.0 × φ²
  - r_fall actor weight: fixed 3.0
  - Impulse: (direction, force, duration) sampled per-episode from weight
    distribution, passed to RelativeImpulsePlugin via episode_options
  - Warm-start: use --resume-from to load from a previous checkpoint

Constructor params (injected via --set on the command line):
  policy_blueprint_path - path to reference policy_blueprint.yaml for internal sim
  weight_npz_path       - path to sample_weights.npz weight distribution file
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

from baseline.framework.ppo.trajectory import ChannelData, RewardChannel, Trajectory
from baseline.framework.rollout import extract_per_step_scalar, extract_per_step_field

from .base import CombatExperimentPPOBase


class WeightedImpulseExperiment(CombatExperimentPPOBase):

    name = "v2_weighted_impulse"

    _channel_names = ("r_fall", "r_cross")
    _gamma = 0.99
    _gae_lambda = 0.95

    env_blueprint = "weighted_impulse_env.yaml"
    agent_used = "both"

    episodes_per_update: int = 256 * 4

    # --- Reward constants ---
    per_step_phi_coef: float = 0.01

    # --- Base actor weights (r_fall fixed, r_cross gated by φ²) ---
    _base_actor_weights: Tuple[float, ...] = (3.0, 1.0)

    _AGENT_IDS = ("robot_a", "robot_b")

    _survival_rate: float = 0.0
    _best_survived: float = -1.0
    _last_best_update: int = 0
    _no_improvement_limit: int = 200
    _min_updates: int = 600
    max_updates: int = 2000

    # --- PPO tuning (conservative for warm-start) ---
    learning_rate: float = 3e-5
    target_kl: float = 0.03
    eval_episodes: int = 512
    eval_interval: int = 5

    def __init__(
        self,
        policy_blueprint_path: Optional[str] = None,
        weight_npz_path: Optional[str] = None,
        direction_jitter: float = 5.0,
        reset_best: bool = False,
    ):
        self._policy_blueprint_path = policy_blueprint_path
        self._sampler: Optional[Any] = None
        if weight_npz_path is not None:
            from baseline.humanoid21.balance_recover.sample_distribution import ImpulseSampler
            self._sampler = ImpulseSampler(weight_npz_path, direction_jitter)
        self._reset_best = reset_best
        self._last_best_update = 0

    def _env_pb(self):
        from envs.framework.parameterized_blueprint import ParameterizedEnvBlueprint
        bp_path = Path(__file__).resolve().parent.parent / "humanoid21" / "balance_recover" / "weighted_impulse_env.yaml"
        return ParameterizedEnvBlueprint.load(bp_path)

    def reward_channels(self) -> Tuple[RewardChannel, ...]:
        return tuple(
            RewardChannel(name=k, gamma=self._gamma, gae_lambda=self._gae_lambda)
            for k in self._channel_names
        )

    # ------------------------------------------------------------------
    # Impulse perturbation parameters (injected via constructor --set)
    # ------------------------------------------------------------------

    def _validate_config(self) -> None:
        if not self._policy_blueprint_path:
            raise ValueError(
                "v2_weighted_impulse requires policy_blueprint_path. "
                "Example: --set policy_blueprint_path=baseline/runs/.../policy_blueprint.yaml"
            )
        if self._sampler is None:
            raise ValueError(
                "v2_weighted_impulse requires weight_npz_path. "
                "Example: --set weight_npz_path=baseline/humanoid21/balance_recover/sample_weights.npz"
            )

    # ------------------------------------------------------------------
    # Job construction — inject impulse params into env materialize
    # ------------------------------------------------------------------

    def build_jobs(
        self,
        policy_bp,
        base_seed: int,
        n_episodes: int,
    ) -> List[Tuple[Any, Any, Any, int, Dict[str, Any]]]:
        self._validate_config()
        env_pb = self._env_pb()
        rng = np.random.default_rng(base_seed)

        env_bp = env_pb.materialize(
            max_steps=self.max_steps,
            policy_blueprint_path=str(Path(self._policy_blueprint_path).resolve()),
        )

        jobs: List[Tuple[Any, Any, Any, int, Dict[str, Any]]] = []
        for i in range(n_episodes):
            seed = int(base_seed + i)
            initial_distance = float(
                rng.uniform(self.init_distance_min, self.init_distance_max)
            )
            sample_rng = np.random.RandomState(seed)
            impulse_params = {
                aid: self._sampler.sample(sample_rng)
                for aid in self._AGENT_IDS
            }
            jobs.append((
                policy_bp, policy_bp,
                env_bp, seed,
                {
                    "initial_distance": initial_distance,
                    "impulse_params": impulse_params,
                },
            ))
        return jobs

    # ------------------------------------------------------------------
    # Trajectory building — identical to crossphi2_impulse
    # ------------------------------------------------------------------

    def _build_agent_trajectory(
        self,
        episode,
        agent_id: str,
        cross_key: str,
        posture_key: str,
        phi_key: str,
    ) -> List[Trajectory]:
        T_full = episode.num_frames
        if T_full == 0:
            return []

        # --- Truncate at agent's termination step ---
        records = episode.agent_termination_proposal_records.get(agent_id, ())
        if records:
            first_reason, term_step = records[0]
            fell = first_reason.startswith("imbalance")
            T = term_step if fell else T_full
        else:
            fell = False
            T = T_full

        if T == 0:
            return []

        obs_all = episode.observations.get(agent_id)
        acts_all = episode.actions.get(agent_id)
        fin_obs = episode.final_observation.get(agent_id)

        if obs_all is None or acts_all is None or fin_obs is None:
            return []

        obs_all = np.asarray(obs_all, dtype=np.float32)
        acts_all = np.asarray(acts_all, dtype=np.float32)

        # --- Extract φ per step ---
        phi_arr = extract_per_step_field(episode.observer_outputs, phi_key, "phi", T_full)
        if phi_arr is not None:
            phi_arr = phi_arr[:T]
        else:
            phi_arr = np.ones(T, dtype=np.float32)
        phi_arr = np.clip(phi_arr, 0.0, 1.0).astype(np.float32)

        # --- r_fall: 0.01 × φ(t) per step only — no terminal signal ---
        r_fall = (self.per_step_phi_coef * phi_arr).astype(np.float32)

        # --- r_cross ---
        r_cross = extract_per_step_scalar(episode.observer_outputs, cross_key, T_full)
        if r_cross is not None:
            r_cross = r_cross[:T]
        else:
            r_cross = np.zeros(T, dtype=np.float32)

        # --- Actor weights: r_fall fixed, r_cross gated by φ² ---
        is_terminated = fell

        # --- Build channels ---
        all_rewards = {
            "r_fall": r_fall,
            "r_cross": r_cross.astype(np.float32),
        }

        actor_weights = {
            "r_fall": np.full(T, self._base_actor_weights[0], dtype=np.float32),
            "r_cross": (self._base_actor_weights[1] * phi_arr ** 2).astype(np.float32),
        }

        channels: Dict[str, ChannelData] = {}
        for idx, key in enumerate(self._channel_names):
            channels[key] = ChannelData(
                reward=all_rewards[key].astype(np.float32),
                is_terminated=is_terminated,
                actor_weight=actor_weights[key],
            )

        return [Trajectory(
            obs=np.asarray(obs_all[:T], dtype=np.float32),
            actions=np.asarray(acts_all[:T], dtype=np.float32),
            last_obs=np.asarray(fin_obs, dtype=np.float32),
            channels=channels,
            importance=1.0,
            mode=None,
        )]

    def build_trajectories(self, episodes) -> List[Trajectory]:
        agent_specs = [
            ("robot_a", "cross_support_a", "posture_a", "height_phi_a"),
            ("robot_b", "cross_support_b", "posture_b", "height_phi_b"),
        ]

        all_trajs: List[Trajectory] = []
        for episode in episodes:
            for agent_id, cross_key, posture_key, phi_key in agent_specs:
                agent_trajs = self._build_agent_trajectory(
                    episode, agent_id, cross_key, posture_key, phi_key,
                )
                all_trajs.extend(agent_trajs)
        return all_trajs

    def on_eval(self, episodes, update) -> Dict[str, Any]:
        survived_count = 0
        total_agents = 0
        for ep in episodes:
            for aid in self._AGENT_IDS:
                total_agents += 1
                term_reason = ep.agent_termination_reason.get(aid, "")
                if not term_reason.startswith("imbalance"):
                    survived_count += 1

        survival_rate = float(survived_count / max(total_agents, 1))
        self._survival_rate = survival_rate

        survived_metric = float(survived_count)
        is_new_best = survived_metric > self._best_survived
        if is_new_best:
            self._best_survived = survived_metric
            self._last_best_update = update

        no_improvement = update - self._last_best_update
        stop_training = (no_improvement >= self._no_improvement_limit
                         and update >= self._min_updates)

        return {
            "is_new_best": is_new_best,
            "stop_training": stop_training,
            "info": {
                "survived": survived_metric,
                "survival_rate": round(survival_rate, 3),
            },
        }

    def state(self) -> dict:
        return {
            "survival_rate": self._survival_rate,
            "best_survived": self._best_survived,
            "last_best_update": self._last_best_update,
        }

    def load_state(self, state: dict) -> None:
        self._survival_rate = float(state.get("survival_rate", 0.0))
        if self._reset_best:
            self._best_survived = -1.0
            self._last_best_update = state.get("update", 0)
        else:
            self._best_survived = float(state.get("best_survived", -1.0))
            self._last_best_update = state.get("last_best_update", state.get("update", 0))


EXPERIMENT_CLASS = WeightedImpulseExperiment
